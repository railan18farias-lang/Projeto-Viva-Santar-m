-- Editable public site copy and photo gallery. Re-runnable without replacing content.
create table if not exists public.site_settings (
  setting_key text primary key check (setting_key ~ '^[a-z0-9_-]{2,80}$'),
  value text not null,
  updated_at timestamptz not null default now()
);

create table if not exists public.gallery_photos (
  id bigint generated by default as identity primary key,
  title text not null,
  alt_text text not null,
  caption text,
  image_path text not null unique,
  is_published boolean not null default true,
  created_at timestamptz not null default now()
);

alter table public.site_settings enable row level security;
alter table public.gallery_photos enable row level security;
revoke all on table public.site_settings, public.gallery_photos from public, anon, authenticated;
grant select on table public.site_settings to anon, authenticated;
grant select on table public.gallery_photos to anon, authenticated;
grant insert, update, delete on table public.site_settings, public.gallery_photos to authenticated;
grant usage, select on sequence public.gallery_photos_id_seq to authenticated;

drop policy if exists "Public can read site settings" on public.site_settings;
create policy "Public can read site settings" on public.site_settings for select to anon using (true);
drop policy if exists "Authenticated can read site settings" on public.site_settings;
create policy "Authenticated can read site settings" on public.site_settings for select to authenticated
  using ((select private.has_site_editor_access()));
drop policy if exists "Site editors insert site settings" on public.site_settings;
create policy "Site editors insert site settings" on public.site_settings for insert to authenticated
  with check ((select private.has_site_editor_access()));
drop policy if exists "Site editors update site settings" on public.site_settings;
create policy "Site editors update site settings" on public.site_settings for update to authenticated
  using ((select private.has_site_editor_access())) with check ((select private.has_site_editor_access()));
drop policy if exists "Site editors delete site settings" on public.site_settings;
create policy "Site editors delete site settings" on public.site_settings for delete to authenticated
  using ((select private.has_site_editor_access()));

drop policy if exists "Public can read published gallery photos" on public.gallery_photos;
create policy "Public can read published gallery photos" on public.gallery_photos for select to anon using (is_published);
drop policy if exists "Authenticated can read gallery photos" on public.gallery_photos;
create policy "Authenticated can read gallery photos" on public.gallery_photos for select to authenticated
  using (is_published or (select private.has_site_editor_access()));
drop policy if exists "Published gallery photos only" on public.gallery_photos;
create policy "Published gallery photos only" on public.gallery_photos as restrictive for select to anon using (is_published);
drop policy if exists "Staff draft visibility guard for gallery photos" on public.gallery_photos;
create policy "Staff draft visibility guard for gallery photos" on public.gallery_photos as restrictive for select to authenticated
  using (is_published or (select private.has_site_editor_access()));
drop policy if exists "Site editors insert gallery photos" on public.gallery_photos;
create policy "Site editors insert gallery photos" on public.gallery_photos for insert to authenticated
  with check ((select private.has_site_editor_access()));
drop policy if exists "Site editors update gallery photos" on public.gallery_photos;
create policy "Site editors update gallery photos" on public.gallery_photos for update to authenticated
  using ((select private.has_site_editor_access())) with check ((select private.has_site_editor_access()));
drop policy if exists "Site editors delete gallery photos" on public.gallery_photos;
create policy "Site editors delete gallery photos" on public.gallery_photos for delete to authenticated
  using ((select private.has_site_editor_access()));

