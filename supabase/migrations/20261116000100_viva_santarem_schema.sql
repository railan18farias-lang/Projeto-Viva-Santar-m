-- Execute no SQL Editor do Supabase. Pode ser executado novamente sem duplicar os dados iniciais.

create table if not exists public.destinations (
    id bigint generated by default as identity primary key,
    name text not null,
    category text not null check (category in ('praias', 'natureza', 'cultura', 'gastronomia')),
    description text not null,
    location text,
    image_path text,
    website_url text,
    is_published boolean not null default true,
    created_at timestamptz not null default now(),
    unique (name, category)
);
alter table public.destinations add column if not exists image_path text;
alter table public.destinations add column if not exists website_url text;
alter table public.destinations add column if not exists is_published boolean not null default true;

create table if not exists public.events (
    id bigint generated by default as identity primary key,
    name text not null,
    description text not null,
    starts_at date not null,
    ends_at date,
    location text not null,
    city text not null,
    image_path text,
    website_url text,
    is_published boolean not null default true,
    created_at timestamptz not null default now(),
    check (ends_at is null or ends_at >= starts_at)
);

create table if not exists public.event_submissions (
    id bigint generated by default as identity primary key,
    name text not null,
    description text not null,
    event_date date,
    location text not null,
    city text not null,
    contact_name text not null,
    contact_email text not null,
    status text not null default 'pending' check (status in ('pending', 'approved', 'rejected')),
    created_at timestamptz not null default now()
);

create table if not exists public.provider_requests (
    id bigint generated by default as identity primary key,
    service_type text not null check (service_type in ('guia', 'transporte')),
    name text not null,
    cadastur text not null,
    contact text not null,
    email text not null,
    status text not null default 'pending' check (status in ('pending', 'approved', 'rejected')),
    created_at timestamptz not null default now()
);
alter table public.provider_requests add column if not exists status text not null default 'pending';

create table if not exists public.itinerary_requests (
    id bigint generated by default as identity primary key,
    days integer not null check (days between 1 and 30),
    interest text not null check (interest in ('praias', 'natureza', 'cultura', 'gastronomia')),
    budget numeric(10,2) check (budget is null or budget >= 0),
    created_at timestamptz not null default now()
);

create table if not exists public.featured_routes (
    id bigint generated by default as identity primary key,
    slug text not null unique,
    title text not null,
    origin text not null,
    destination text not null,
    transport text,
    estimated_duration text,
    description text not null,
    maps_url text,
    details jsonb not null default '{}'::jsonb,
    is_published boolean not null default true,
    created_at timestamptz not null default now()
);

create table if not exists public.assistant_responses (
    id bigint generated by default as identity primary key,
    intent text not null unique,
    response text not null,
    is_published boolean not null default true,
    updated_at timestamptz not null default now()
);

-- Acesso público: leitura apenas de conteúdo publicado; formulários só podem inserir.
alter table public.destinations enable row level security;
alter table public.events enable row level security;
alter table public.event_submissions enable row level security;
alter table public.provider_requests enable row level security;
alter table public.itinerary_requests enable row level security;
alter table public.featured_routes enable row level security;
alter table public.assistant_responses enable row level security;

drop policy if exists "Public can read destinations" on public.destinations;
create policy "Public can read destinations" on public.destinations for select to anon, authenticated using (is_published);
drop policy if exists "Published destinations only" on public.destinations;
create policy "Published destinations only" on public.destinations as restrictive for select to anon, authenticated using (is_published);
drop policy if exists "Public can read events" on public.events;
create policy "Public can read events" on public.events for select to anon, authenticated using (is_published);
drop policy if exists "Published events only" on public.events;
create policy "Published events only" on public.events as restrictive for select to anon, authenticated using (is_published);
drop policy if exists "Public can read featured routes" on public.featured_routes;
create policy "Public can read featured routes" on public.featured_routes for select to anon, authenticated using (is_published);
drop policy if exists "Published routes only" on public.featured_routes;
create policy "Published routes only" on public.featured_routes as restrictive for select to anon, authenticated using (is_published);
drop policy if exists "Public can read assistant responses" on public.assistant_responses;
create policy "Public can read assistant responses" on public.assistant_responses for select to anon, authenticated using (is_published);
drop policy if exists "Published assistant responses only" on public.assistant_responses;
create policy "Published assistant responses only" on public.assistant_responses as restrictive for select to anon, authenticated using (is_published);

drop policy if exists "Public can submit provider requests" on public.provider_requests;
create policy "Public can submit provider requests" on public.provider_requests for insert to anon, authenticated with check (status = 'pending');
drop policy if exists "Provider submissions stay pending" on public.provider_requests;
create policy "Provider submissions stay pending" on public.provider_requests as restrictive for insert to anon, authenticated with check (status = 'pending');
drop policy if exists "Public can submit itinerary requests" on public.itinerary_requests;
create policy "Public can submit itinerary requests" on public.itinerary_requests for insert to anon, authenticated with check (true);
drop policy if exists "Public can submit event suggestions" on public.event_submissions;
create policy "Public can submit event suggestions" on public.event_submissions for insert to anon, authenticated with check (status = 'pending');
drop policy if exists "Event suggestions stay pending" on public.event_submissions;
create policy "Event suggestions stay pending" on public.event_submissions as restrictive for insert to anon, authenticated with check (status = 'pending');

-- Remove permissões antigas/amplas apenas das tabelas deste aplicativo e conceder o mínimo necessário.
revoke all privileges on table public.destinations, public.events, public.event_submissions,
    public.provider_requests, public.itinerary_requests, public.featured_routes,
    public.assistant_responses from PUBLIC, anon, authenticated;
grant select on public.destinations, public.events, public.featured_routes, public.assistant_responses to anon, authenticated;
grant insert (service_type, name, cadastur, contact, email) on table public.provider_requests to anon, authenticated;
grant insert (days, interest, budget) on table public.itinerary_requests to anon, authenticated;
grant insert (name, description, event_date, location, city, contact_name, contact_email) on table public.event_submissions to anon, authenticated;
revoke all privileges on sequence public.destinations_id_seq, public.events_id_seq,
    public.event_submissions_id_seq, public.provider_requests_id_seq,
    public.itinerary_requests_id_seq, public.featured_routes_id_seq,
    public.assistant_responses_id_seq from PUBLIC, anon, authenticated;
grant usage on sequence public.provider_requests_id_seq, public.itinerary_requests_id_seq,
    public.event_submissions_id_seq to anon, authenticated;

